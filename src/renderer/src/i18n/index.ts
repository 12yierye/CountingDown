export type MessageSchema = (typeof messages)['zh-CN']

export function createAppI18n(language: AppLanguage = 'zh-CN') {
  return createI18n({
    legacy: false,
    globalInjection: true,
    locale: language,
    fallbackLocale: 'zh-CN',
    messages
  })
}

export function readStoredLanguage(): AppLanguage {
  try {
    const value = localStorage.getItem('cd.language')
    if (value === 'en-US' || value === 'zh-CN') return value
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export function storeLanguage(language: AppLanguage): void {
  try {
    localStorage.setItem('cd.language', language)
  } catch {
    /* ignore */
  }
}
